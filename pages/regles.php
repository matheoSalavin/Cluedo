    <h1>Règles du jeu</h1>

    <h2>Objectif</h2>
    <p>
        Le but du jeu est de découvrir le personnage coupable,
        l'arme utilisée et la pièce où le crime a été commis.
    </p>

    <h2>Déroulement d'une partie</h2>
    <ol>
        <li>Choisissez un personnage pour commencer l'enquête.</li>
        <li>Une solution secrète est tirée au hasard par le jeu.</li>
        <li>Vous commencez votre enquête dans le Hall.</li>
        <li>Déplacez-vous dans les pièces accessibles par les portes.</li>
        <li>Dans une pièce, vous pouvez faire une hypothèse en choisissant un personnage et une arme.</li>
    </ol>

    <h2>Les hypothèses</h2>
    <p>
        Une hypothèse permet de vérifier si le personnage et l'arme
        choisis, ainsi que la pièce où vous vous trouvez,
        correspondent à la solution secrète.
    </p>
    <p>
        Si votre hypothèse est incorrecte, le jeu vous indique
        un des éléments qui n'est pas le bon.
        Vous pouvez alors continuer votre enquête.
    </p>

    <h2>La victoire</h2>
    <p>
        Lorsque vous trouvez les trois bons éléments,
        vous remportez la partie.
        Un récapitulatif affiche alors la solution,
        le nombre d'hypothèses et les pièces visitées.
    </p>

